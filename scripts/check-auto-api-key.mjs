import assert from 'node:assert/strict';
import { hasUserApiKey, isAutoGeneratedToken } from '../src/utils/tokenForm.js';

const automaticKeys = [
  { name: 'chat-auto-1001' },
  { name: 'system-auto-1002' },
];

assert.equal(automaticKeys.every(isAutoGeneratedToken), true);
assert.equal(hasUserApiKey(automaticKeys), false);
assert.equal(hasUserApiKey([...automaticKeys, { name: 'Default API Key' }]), true);
assert.equal(hasUserApiKey([]), false);

console.log('Automatic API key check passed.');
